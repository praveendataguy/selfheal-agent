"""The self-healing loop: failed pipeline -> diagnose -> guarded patch -> MR -> re-run (or ask a human)."""

import logging
import re
from typing import Callable

from app import log_parser, policy
from app.approval import ApprovalRequest, Notifier
from app.config import Settings
from app.gitlab_client import GitLabClient
from app.llm import BaseDiagnoser, make_diagnoser
from app.models import Diagnosis, FailureCategory, FailureContext, FileChange, Risk
from app.observability import event, recent_runtime_errors

log = logging.getLogger(__name__)

ATTEMPT_RE = re.compile(r"^Self-Heal-Attempt:\s*(\d+)\s*$", re.MULTILINE)
TARGET_RE = re.compile(r"^Self-Heal-Target:\s*(\S+)\s*$", re.MULTILINE)
SOURCE_RE = re.compile(r"^Self-Heal-Source-Pipeline:\s*(\d+)\s*$", re.MULTILINE)

MANIFESTS = [
    "requirements.txt", "pyproject.toml", "setup.py", "setup.cfg", "Pipfile", "poetry.lock",
    "package.json", "go.mod", "pom.xml", "build.gradle", "Cargo.toml", "Gemfile", "composer.json",
]
CONTEXT_BUDGET_CHARS = 150_000

DiagnoserFactory = Callable[[Settings, Callable[[str], str | None], Callable[[str], list[str]]], BaseDiagnoser]


def slugify(ref: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", ref).strip("-")[:60]


class Orchestrator:
    def __init__(
        self,
        settings: Settings,
        gitlab: GitLabClient,
        notifier: Notifier,
        diagnoser_factory: DiagnoserFactory = make_diagnoser,
    ):
        self.s = settings
        self.gl = gitlab
        self.notifier = notifier
        self.diagnoser_factory = diagnoser_factory

    # ------------------------------------------------------------------ entry
    def handle_pipeline_event(self, payload: dict) -> str:
        attrs = payload.get("object_attributes", {})
        status, ref = attrs.get("status"), attrs.get("ref", "")
        project_id, pipeline_id = payload.get("project", {}).get("id"), attrs.get("id")
        if not project_id or not pipeline_id:
            return "ignored: malformed payload"

        if status == "success" and ref.startswith(self.s.branch_prefix):
            return self._on_fix_verified(project_id, pipeline_id, ref, payload)
        if self.s.healer == "duo" and status in ("success", "failed"):
            return self._duo_pipeline_outcome(project_id, pipeline_id, ref, status, payload)
        if status != "failed":
            return f"ignored: status={status}"
        return self.heal(project_id, pipeline_id)

    # ------------------------------------------------- Duo governance mode
    def _is_duo_mr(self, mr: dict) -> bool:
        prefixes = self.s._split(self.s.duo_author_prefixes)
        if self.s.governed_label in mr["labels"]:
            return True
        if mr["source_branch"].startswith((self.s.branch_prefix, "duo/")):
            return True
        if "[FixPipeline]" in mr["title"]:  # GitLab's Fix CI/CD Pipeline flow
            return True
        return any(mr["author"].lower().startswith(p.lower()) for p in prefixes)

    def handle_merge_request_event(self, payload: dict) -> str:
        """A Duo flow opened (or updated) a fix MR: run guardrails, then auto-verify or ask a human."""
        if self.s.healer != "duo":
            return "ignored: healer is not duo"
        attrs = payload.get("object_attributes", {})
        project_id, mr_iid = payload.get("project", {}).get("id"), attrs.get("iid")
        if attrs.get("action") not in ("open", "reopen") or not project_id or not mr_iid:
            return f"ignored: action={attrs.get('action')}"
        mr = self.gl.get_mr(project_id, mr_iid)
        if not self._is_duo_mr(mr):
            return "ignored: not a Duo fix MR"
        if "Generated by the self-heal agent" in mr["description"]:
            return "ignored: our own MR"

        project_path = payload.get("project", {}).get("path_with_namespace", str(project_id))
        fields = {"project": project_path, "mr_iid": mr_iid, "author": mr["author"]}
        event("duo.mr_received", **fields)

        changes = []
        for path, deleted in self.gl.mr_changed_paths(project_id, mr_iid):
            content = "" if deleted else (self.gl.read_file(project_id, path, mr["source_branch"]) or "")
            changes.append(FileChange(path, content))
        old_files = {}
        for c in changes:
            old = self.gl.read_file(project_id, c.path, mr["target_branch"])
            if old is not None:
                old_files[c.path] = old

        diagnosis = Diagnosis(
            category=FailureCategory.UNKNOWN,
            root_cause=mr["title"],
            explanation=mr["description"],
            confidence=1.0,  # Duo's own judgement; guardrails below still apply
            risk=Risk.LOW,
            retry_only=False,
            changes=changes,
        )
        ctx = FailureContext(
            project_id=project_id, project_path=project_path, pipeline_id=0, ref=mr["target_branch"],
            sha="", commit_title=mr["title"], jobs=[], files=old_files, original_ref=mr["target_branch"],
        )
        decision = policy.evaluate(diagnosis, ctx, self.s)
        self.gl.update_mr(project_id, mr_iid, add_labels=[self.s.governed_label, "duo-flow"])
        reasons = "\n".join(f"- {r}" for r in decision.reasons) or "- none"

        if not decision.allowed:
            self.gl.update_mr(project_id, mr_iid, add_labels=["self-heal::blocked"])
            self.gl.comment_mr(
                project_id, mr_iid,
                f"🛑 **Self-heal governance blocked this Duo fix.**\n\n{reasons}\n\nA human must review it manually.",
            )
            self.notifier.notify(
                f":octagonal_sign: Governance blocked a Duo fix for *{project_path}* — "
                f"<{mr['web_url']}|MR !{mr_iid}>: {'; '.join(decision.reasons)}"
            )
            event("fix.blocked", reasons=decision.reasons, **fields)
            return "blocked: " + "; ".join(decision.reasons)

        if decision.needs_approval:
            if not mr["title"].lower().startswith("draft"):
                self.gl.update_mr(project_id, mr_iid, title=f"Draft: {mr['title']}")
            self.gl.comment_mr(
                project_id, mr_iid,
                f"⚠️ **Human approval required** before this Duo fix is verified:\n\n{reasons}\n\nApprove or reject in Slack.",
            )
            self.notifier.request_approval(
                ApprovalRequest(
                    project_id=project_id, project_path=project_path, mr_iid=mr_iid, mr_url=mr["web_url"],
                    branch=mr["source_branch"], target_ref=mr["target_branch"], pipeline_id=0,
                    root_cause=f"(GitLab Duo flow) {mr['title']}", category="duo_fix", confidence=1.0,
                    risk="governed", reasons=decision.reasons, files=[c.path for c in changes],
                )
            )
            event("approval.requested", **fields)
            return f"awaiting approval: {mr['web_url']}"

        pipeline_id = self.gl.run_pipeline(project_id, mr["source_branch"])
        self.gl.comment_mr(
            project_id, mr_iid,
            f"✅ **Self-heal governance passed** (no policy concerns). Verification pipeline #{pipeline_id} started.",
        )
        event("fix.auto_verified", pipeline_id=pipeline_id, **fields)
        return f"verifying: pipeline #{pipeline_id}"

    def _duo_pipeline_outcome(self, project_id: int, pipeline_id: int, ref: str, status: str, payload: dict) -> str:
        path = payload.get("project", {}).get("path_with_namespace", str(project_id))
        mr_ref = self.gl.find_open_mr(project_id, ref)
        mr = self.gl.get_mr(project_id, mr_ref.iid) if mr_ref else None
        if not mr or not self._is_duo_mr(mr):
            if status == "failed":
                event("pipeline.failed", project=path, pipeline_id=pipeline_id, ref=ref, handler="duo_flow")
                return "left to Duo flow"
            return "ignored: success outside a fix MR"
        if status == "success":
            self.gl.comment_mr(project_id, mr["iid"], f"🟢 Pipeline #{pipeline_id} passed with the Duo fix.")
            self.notifier.notify(
                f":white_check_mark: Duo fix verified for *{path}* — <{mr['web_url']}|MR !{mr['iid']}> is ready for review."
            )
            event("fix.verified", project=path, pipeline_id=pipeline_id, source="duo")
            return "verified"
        self.gl.comment_mr(project_id, mr["iid"], f"🔴 Pipeline #{pipeline_id} failed with the Duo fix. Needs a human.")
        self.notifier.notify(
            f":x: Duo fix failed verification for *{path}* — <{mr['web_url']}|MR !{mr['iid']}> needs a human."
        )
        event("fix.failed_verification", project=path, pipeline_id=pipeline_id)
        return "fix failed verification"

    def heal(self, project_id: int, pipeline_id: int) -> str:
        info = self.gl.pipeline_info(project_id, pipeline_id)
        fields = {"project": info.project_path, "pipeline_id": pipeline_id, "ref": info.ref}
        event("pipeline.failed", **fields)

        # ---- incident bookkeeping (stateless: lives in branch names + commit trailers)
        if info.ref.startswith(self.s.branch_prefix):
            m = ATTEMPT_RE.search(info.commit_message)
            target = TARGET_RE.search(info.commit_message)
            if not m or not target:
                return "ignored: self-heal branch has a human commit on top"
            attempt, original_ref, branch = int(m.group(1)) + 1, target.group(1), info.ref
            src = SOURCE_RE.search(info.commit_message)
            source_pipeline = int(src.group(1)) if src else pipeline_id
            mr = self.gl.find_open_mr(project_id, branch)
            if attempt > self.s.max_attempts:
                msg = (
                    f":x: Self-heal gave up on *{info.project_path}* `{original_ref}` after "
                    f"{self.s.max_attempts} attempts. Human attention needed."
                    + (f" <{mr.web_url}|MR !{mr.iid}>" if mr else "")
                )
                self.notifier.notify(msg)
                if mr:
                    self.gl.comment_mr(project_id, mr.iid, "Self-heal reached its attempt limit; stopping.")
                event("incident.exhausted", **fields)
                return "stopped: attempt limit"
        else:
            attempt, original_ref, source_pipeline = 1, info.ref, pipeline_id
            branch = f"{self.s.branch_prefix}{slugify(info.ref)}-{pipeline_id}"
            mr = None
            if self.gl.branch_exists(project_id, branch):
                return "ignored: already handling this pipeline"

        jobs = self.gl.failed_jobs(project_id, pipeline_id)
        if not jobs:
            return "ignored: no blocking failed jobs"
        for job in jobs:
            job.log = log_parser.excerpt(job.log, self.s.max_log_chars // max(1, len(jobs)))
        category = log_parser.classify("\n".join(j.log for j in jobs))

        # ---- cheap path: transient infra failure -> retry once, no LLM call
        if category == FailureCategory.INFRA_FLAKE and self._retry_once(project_id, pipeline_id, jobs):
            event("pipeline.retried", reason="infra_flake", **fields)
            return "retried: transient failure"

        ctx = FailureContext(
            project_id=project_id,
            project_path=info.project_path,
            pipeline_id=pipeline_id,
            ref=info.ref,
            sha=info.sha,
            commit_title=info.commit_title,
            jobs=jobs,
            heuristic_category=category,
            attempt=attempt,
            original_ref=original_ref,
        )
        self._gather_files(ctx)
        if self.s.fetch_cloud_logging_context and self.s.gcp_project_id and category in (
            FailureCategory.DEPLOYMENT_DRIFT,
            FailureCategory.MEMORY,
        ):
            ctx.extra_context = recent_runtime_errors(self.s.gcp_project_id, info.project_path.split("/")[-1])

        diagnoser = self.diagnoser_factory(
            self.s,
            lambda path: self.gl.read_file(project_id, path, info.sha),
            lambda path: self.gl.list_tree(project_id, info.sha, path),
        )
        diagnosis = diagnoser.diagnose(ctx)
        event(
            "diagnosis.done",
            category=diagnosis.category.value,
            confidence=diagnosis.confidence,
            files=len(diagnosis.changes),
            **fields,
        )

        if diagnosis.retry_only:
            if self._retry_once(project_id, pipeline_id, jobs):
                event("pipeline.retried", reason="model", **fields)
                return "retried: model judged failure transient"
            self._report_only(ctx, diagnosis, ["retry already attempted; failure persists"], mr)
            return "reported: transient failure persisted"

        decision = policy.evaluate(diagnosis, ctx, self.s)
        if not decision.allowed:
            self._report_only(ctx, diagnosis, decision.reasons, mr)
            event("fix.blocked", reasons=decision.reasons, **fields)
            return "reported: " + "; ".join(decision.reasons)

        if self.s.dry_run:
            event("fix.dry_run", needs_approval=decision.needs_approval, **fields)
            return "dry-run: patch generated but not pushed"

        # ---- push the patch
        existing = {c.path for c in diagnosis.changes if c.path in ctx.files} | {
            c.path
            for c in diagnosis.changes
            if c.path not in ctx.files and self.gl.read_file(project_id, c.path, info.sha) is not None
        }
        skip_ci = " [skip ci]" if decision.needs_approval else ""
        message = (
            f"fix({diagnosis.category.value}): {_one_line(diagnosis.root_cause, 60)}{skip_ci}\n\n"
            f"{diagnosis.explanation[:3000]}\n\n"
            f"Self-Heal-Attempt: {attempt}\n"
            f"Self-Heal-Target: {original_ref}\n"
            f"Self-Heal-Source-Pipeline: {source_pipeline}\n"
        )
        self.gl.commit_changes(
            project_id,
            branch,
            diagnosis.changes,
            message,
            start_sha=info.sha if attempt == 1 else None,
            existing_paths=existing,
        )

        description = self._mr_description(ctx, diagnosis, decision.reasons, decision.needs_approval)
        if mr is None:
            draft = "Draft: " if decision.needs_approval else ""
            mr = self.gl.open_mr(
                project_id,
                source=branch,
                target=original_ref,
                title=f"{draft}🤖 Self-heal: {_one_line(diagnosis.root_cause, 80)}",
                description=description,
                labels=["self-heal", f"failure::{diagnosis.category.value}"],
            )
        else:
            self.gl.comment_mr(project_id, mr.iid, f"### Attempt {attempt}\n\n{description}")
        event("fix.mr_opened", mr_url=mr.web_url, attempt=attempt, needs_approval=decision.needs_approval, **fields)

        if decision.needs_approval:
            self.notifier.request_approval(
                ApprovalRequest(
                    project_id=project_id,
                    project_path=info.project_path,
                    mr_iid=mr.iid,
                    mr_url=mr.web_url,
                    branch=branch,
                    target_ref=original_ref,
                    pipeline_id=pipeline_id,
                    root_cause=diagnosis.root_cause,
                    category=diagnosis.category.value,
                    confidence=diagnosis.confidence,
                    risk=diagnosis.risk.value,
                    reasons=decision.reasons,
                    files=[c.path for c in diagnosis.changes],
                )
            )
            event("approval.requested", **fields)
            return f"awaiting approval: {mr.web_url}"
        # Pushing the branch triggers its pipeline automatically.
        return f"patched: {mr.web_url}"

    # ------------------------------------------------------------- approvals
    def handle_decision(self, approved: bool, project_id: int, mr_iid: int, branch: str, user: str) -> str:
        if not branch.startswith(self.s.branch_prefix):
            # Duo flows pick their own branch names: only act on MRs we labelled as governed.
            mr = self.gl.get_mr(project_id, mr_iid) if self.s.healer == "duo" else None
            if not mr or mr["source_branch"] != branch or self.s.governed_label not in mr["labels"]:
                raise ValueError("refusing to act on a non self-heal branch")
        if approved:
            self.gl.mark_mr_ready(project_id, mr_iid)
            pipeline_id = self.gl.run_pipeline(project_id, branch)
            self.gl.comment_mr(project_id, mr_iid, f"✅ Approved in Slack by {user}. Pipeline #{pipeline_id} started.")
            event("approval.granted", project_id=project_id, mr_iid=mr_iid, user=user)
            return f"Approved by {user}; pipeline #{pipeline_id} started."
        self.gl.comment_mr(project_id, mr_iid, f"🚫 Rejected in Slack by {user}. Closing.")
        self.gl.close_mr(project_id, mr_iid)
        self.gl.delete_branch(project_id, branch)
        event("approval.rejected", project_id=project_id, mr_iid=mr_iid, user=user)
        return f"Rejected by {user}; MR closed."

    # --------------------------------------------------------------- helpers
    def _on_fix_verified(self, project_id: int, pipeline_id: int, ref: str, payload: dict) -> str:
        message = payload.get("commit", {}).get("message", "")
        if not ATTEMPT_RE.search(message):
            return "ignored: success on non-agent commit"
        mr = self.gl.find_open_mr(project_id, ref)
        path = payload.get("project", {}).get("path_with_namespace", str(project_id))
        if mr:
            self.gl.comment_mr(project_id, mr.iid, f"🟢 Pipeline #{pipeline_id} passed with the self-heal patch.")
        self.notifier.notify(
            f":white_check_mark: Self-heal fix verified for *{path}*"
            + (f" — <{mr.web_url}|MR !{mr.iid}> is ready for review." if mr else ".")
        )
        event("fix.verified", project=path, pipeline_id=pipeline_id)
        return "verified"

    def _retry_once(self, project_id: int, pipeline_id: int, jobs) -> bool:
        retried = False
        for job in jobs:
            if self.gl.job_run_count(project_id, pipeline_id, job.name) <= 1:
                self.gl.retry_job(project_id, job.id)
                retried = True
        return retried

    def _gather_files(self, ctx: FailureContext) -> None:
        try:
            ctx.changed_files = self.gl.changed_files(ctx.project_id, ctx.sha)
        except Exception:  # noqa: BLE001
            log.warning("could not read commit diff", exc_info=True)
        candidates: list[str] = []
        for job in ctx.jobs:
            candidates += log_parser.referenced_paths(job.log)
        candidates += ctx.changed_files
        if ctx.heuristic_category in (FailureCategory.DEPENDENCY_CONFLICT, FailureCategory.BUILD_ERROR):
            candidates += MANIFESTS
        if ctx.heuristic_category in (FailureCategory.MEMORY, FailureCategory.DEPLOYMENT_DRIFT):
            candidates += [".gitlab-ci.yml"]

        used = 0
        for path in dict.fromkeys(candidates):  # dedupe, keep order
            if path in ctx.files or used >= CONTEXT_BUDGET_CHARS:
                continue
            content = self.gl.read_file(ctx.project_id, path, ctx.sha)
            if content is None or "\x00" in content[:1000]:
                continue
            ctx.files[path] = content
            used += min(len(content), 40_000)

    def _report_only(self, ctx: FailureContext, d: Diagnosis, reasons: list[str], mr) -> None:
        text = (
            f":mag: *Pipeline failure analysed (no patch applied)* — {ctx.project_path} `{ctx.ref}` "
            f"pipeline #{ctx.pipeline_id}\n*Category:* {d.category.value} · *Confidence:* {d.confidence:.0%}\n"
            f"*Root cause:* {d.root_cause}\n*Why no patch:* {'; '.join(reasons)}"
        )
        self.notifier.notify(text)
        if mr:
            self.gl.comment_mr(ctx.project_id, mr.iid, text.replace(":mag: ", ""))

    def _mr_description(self, ctx: FailureContext, d: Diagnosis, reasons: list[str], gated: bool) -> str:
        jobs = "\n".join(f"- `{j.name}` (stage `{j.stage}`, job {j.id})" for j in ctx.jobs)
        files = "\n".join(f"- `{c.path}`" for c in d.changes)
        gate = (
            "\n\n> ⚠️ **Human approval required** before this patch runs: "
            + "; ".join(reasons)
            + ". Approve or reject in Slack."
            if gated
            else ""
        )
        return (
            f"## 🤖 Automated fix for pipeline #{ctx.pipeline_id}\n\n"
            f"**Root cause:** {d.root_cause}\n\n"
            f"**Category:** `{d.category.value}` · **Confidence:** {d.confidence:.0%} · **Risk:** {d.risk.value}"
            f"{gate}\n\n### Failed jobs\n{jobs}\n\n### Analysis\n{d.explanation}\n\n### Files changed\n{files}\n\n"
            f"---\n_Generated by the self-heal agent (attempt {ctx.attempt}/{self.s.max_attempts}). "
            f"Review before merging._"
        )


def _one_line(text: str, limit: int) -> str:
    line = " ".join(text.split())
    return line if len(line) <= limit else line[: limit - 1] + "…"
